"""Copies the shared scenario content into web/content.js so the site also works when opened from disk.

Run from the repo root after editing ios/InterAIct/Resources/scenarios.json:
    python3 web/build_content.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "ios", "InterAIct", "Resources", "scenarios.json")
TARGET = os.path.join(ROOT, "web", "content.js")
HEADER = "// Generated by web/build_content.py from ios/InterAIct/Resources/scenarios.json. Do not edit.\n"


def render():
    with open(SOURCE, encoding="utf-8") as f:
        catalog = json.load(f)
    body = json.dumps(catalog, ensure_ascii=False, indent=2)
    return f"{HEADER}window.INTERAICT_CONTENT = {body};\n"


if __name__ == "__main__":
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(render())
    print(f"Wrote {os.path.relpath(TARGET, ROOT)}")
